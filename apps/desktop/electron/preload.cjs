const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('desktop', {
  quit: () => ipcRenderer.invoke('app:quit'),
  audioOpen: options => ipcRenderer.invoke('audio:open', options),
  audioBounds: options => ipcRenderer.invoke('audio:bounds', options),
  audioClose: id => ipcRenderer.invoke('audio:close', id),
  audioSend: message => ipcRenderer.send('audio:message', message),
  audioListen: callback => { const listener = (_event, message) => callback(message); ipcRenderer.on('audio:message', listener); return () => ipcRenderer.removeListener('audio:message', listener); },
  setAutoStart: enabled => ipcRenderer.invoke('app:auto-start', enabled),
  setSecondDisplay: enabled => ipcRenderer.invoke('display:set-enabled', enabled),
  selectBackgroundMusic: () => ipcRenderer.invoke('music:select'),
  loadBackgroundMusic: () => ipcRenderer.invoke('music:load'),
  selectLocalLibrary: () => ipcRenderer.invoke('library:select'),
  loadLocalLibrary: () => ipcRenderer.invoke('library:load'),
  loadYoutubeKey: () => ipcRenderer.invoke('youtube:load-key'),
  saveYoutubeKey: key => ipcRenderer.invoke('youtube:save-key', key),
  savePhoto: photo => ipcRenderer.invoke('photos:save', photo),
  listPhotos: () => ipcRenderer.invoke('photos:list'),
  readPhoto: id => ipcRenderer.invoke('photos:read', id),
  deletePhoto: id => ipcRenderer.invoke('photos:delete', id),
  selectPhotoFolder: () => ipcRenderer.invoke('photos:select-folder'),
  getPhotoFolder: () => ipcRenderer.invoke('photos:get-folder'),
  remoteStart: () => ipcRenderer.invoke('remote:start'),
  remoteConfigure: permanent => ipcRenderer.invoke('remote:configure', permanent),
  remoteStop: () => ipcRenderer.invoke('remote:stop'),
  remoteListen: callback => { const listener = (_event, request) => callback(request); ipcRenderer.on('remote:request', listener); return () => ipcRenderer.removeListener('remote:request', listener); },
  remoteReply: reply => ipcRenderer.send('remote:reply', reply),
});
